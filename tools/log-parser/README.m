# 柏楚日志解析系统

## 解决什么现场问题

柏楚控制系统报警后，人工翻日志找原因耗时 1 小时起步，难以发现周期性故障规律。

## 功能

- 自动扫描日志目录，识别日期范围
- 提取关键事件：报警代码、复位次数、加工中断原因
- 统计日/周/月的设备利用率、报警频次
- 输出结构化 CSV，便于进一步分析

## 技术点

- Python 文本解析与正则匹配
- 时间序列数据处理
- 简单统计分析（频次、时长）

## 使用示例

```bash
python log_parser.py --log-dir ./logs/ --start 2026-04-01 --end 2026-04-30
```

## 效果

- 故障排查时间从 1 小时（逐行翻日志）降到 5 分钟（筛选关键事件）
- 发现某报警在每周一早晨高频出现，定位到周末关机后冷启动参数漂移问题
